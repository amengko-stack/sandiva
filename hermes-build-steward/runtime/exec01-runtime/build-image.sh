#!/bin/sh
set -eu
case "${1:-}" in *@sha256:????????????????????????????????????????????????????????????????) ;; *) echo "build image must be digest pinned" >&2; exit 2;; esac
case "${2:-}" in *@sha256:????????????????????????????????????????????????????????????????) ;; *) echo "executor image must be digest pinned" >&2; exit 2;; esac
tag="${3:-sandiva-exec01-runtime:code-qa}"
epoch="${SOURCE_DATE_EPOCH:-1704067200}"
context="$(CDPATH= cd -- "$(dirname "$0")" && pwd)"
archive="$(mktemp)"
trap 'rm -f "$archive"' EXIT HUP INT TERM
tar --sort=name --mtime="@$epoch" --owner=0 --group=0 --numeric-owner \
  --exclude='__pycache__' --exclude='*.pyc' --exclude='*.pyo' \
  -C "$context" -cf "$archive" .
docker buildx build --pull=false --provenance=false \
  --build-arg "SOURCE_DATE_EPOCH=$epoch" \
  --build-arg "BUILD_IMAGE=$1" --build-arg "EXECUTOR_IMAGE=$2" \
  --output "type=docker,name=$tag,rewrite-timestamp=true" \
  -f "$context/Dockerfile" - < "$archive"
docker image inspect "$tag" --format '{{.Id}}'
